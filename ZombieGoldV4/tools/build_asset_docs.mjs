// One cast table drives the game, preview and this generated handoff inventory.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { castRoles } from '../src/content/cast.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'assets/spine/catalog.json'), 'utf8'));
const roles = castRoles();
const used = catalog.skeletons.filter(s => roles.has(s.key));
const escape = s => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ');
const rows = catalog.skeletons.map(s => `| \`${s.key}\` | ${escape((roles.get(s.key) || ['未上场，保留原件']).join('；'))} | ${escape(s.animations.join('、'))} | ${s.atlas.join(' × ')} |`);
const text = `# 末日版素材清单

<!-- Generated by tools/build_asset_docs.mjs; edit src/content/cast.js, then regenerate. -->

共导入 ${catalog.skeletons.length} 套 Spine，演员表使用 ${used.length} 套，${catalog.skeletons.length - used.length} 套保留未上场。网页运行时读取 JSON、atlas 和图片；主角与炮台的二进制原件及转换工具也保留在工程中。

运行库为本地 Spine 3.6；原始导出版本、动作与来源记录在 [catalog.json](../assets/spine/catalog.json)，逐个原始路径见素材目录中的 source.txt。主角是 hero/jszc_character01，背影组成跑关队伍；成群敌人烘焙为序列帧，Boss、战场主角及大型目标使用实时骨骼。

预览入口：[全部素材](../tools/spine3d.html)、[人群效果](../tools/spine3d.html#crowd)。选择角色后可切动作与镜像。

修改角色映射、动作、高度请编辑 [演员表](../src/content/cast.js)，不要手动编辑下表。生成：\`node tools/build_asset_docs.mjs\`；检查是否同步：\`node tools/build_asset_docs.mjs --check\`。预览页与本表共用 \`castRoles()\`。

| 素材键 | 游戏角色 | 原始动作 | 图集尺寸 |
|---|---|---|---|
${rows.join('\n')}

未上场素材没有删除；发布包只带演员表登记的素材，\`batch2/41100047\` 延续接手工程的排除设置。本轮浏览器已验证 49 套均可解析；能加载不等于所有动作都适合当前玩法。

3D 道具仍来自原 V9.5 的 Quaternius 资源（车、箱、桥、门框），粒子与 HUD 件沿用现有包。旧鱼卡、海豹立绘和翻牌图片留在原始工程，当前运行界面已使用 Spine 头像和 CSS 补给卡，不再依赖它们。来源与许可记录见 [CREDITS](../assets/CREDITS.md) 和 [Spine runtime](../vendor/spine-3.6/README.md)。
`;
const target = path.join(root, 'docs/素材清单.md');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) {
    console.error('素材清单与演员表不同步：运行 node tools/build_asset_docs.mjs');
    process.exitCode = 1;
  } else console.log(`素材清单已同步：${catalog.skeletons.length} 套素材，${used.length} 套使用中`);
} else {
  fs.writeFileSync(target, text);
  console.log(`docs/素材清单.md：${catalog.skeletons.length} 套素材，${used.length} 套使用中`);
}
