"""Copy the art team's Spine exports into assets/spine/ and rebuild the catalog.

    python3 tools/import_spine.py <inbox folder>

The inbox is the folder the art team hands over (currently "僵尸游戏动画").
Each skeleton lands in assets/spine/<group>/<name>/ with its .json, .atlas.txt
and .png; binary skeletons are also converted to JSON (tools/skel2json.py),
because the web runtime only reads JSON. Re-running is safe: files are
overwritten and the catalog is rebuilt from what is in assets/spine/.

assets/spine/catalog.json lists every skeleton: key, source path, canvas size,
animations, events and atlas size. src/content/ refers to skeletons by key.
"""
import json
import os
import shutil
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import skel2json  # noqa: E402

OUT = os.path.join(ROOT, 'assets', 'spine')

# Inbox sub-folder → group name in assets/spine. Folder names stay ASCII for the web and for engines.
GROUPS = {
    '20251208第一批': 'batch1',
    '20260126第二批': 'batch2',
    'BOSS宝箱怪202608': 'boss',
    '主角': 'hero',
    '展示角色': 'hero',
    '技能炮台': 'turret',
}


def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    return struct.unpack('>II', head[16:24])


def find_skeletons(inbox):
    """Yields (group, source dir, base name, skeleton file) for every skeleton in the inbox."""
    for top in sorted(os.listdir(inbox)):
        group = GROUPS.get(top)
        if not group:
            continue
        for dirpath, _, files in os.walk(os.path.join(inbox, top)):
            for f in sorted(files):
                if f.endswith('.atlas.txt'):
                    base = f[: -len('.atlas.txt')]
                    for ext in ('.json', '.skel.bytes', '.skel'):
                        if base + ext in files:
                            yield group, dirpath, base, base + ext
                            break


def import_inbox(inbox):
    count = 0
    for group, src, base, skel in find_skeletons(inbox):
        dst = os.path.join(OUT, group, base)
        os.makedirs(dst, exist_ok=True)
        for f in (base + '.atlas.txt', base + '.png', skel):
            shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
        if not skel.endswith('.json'):
            with open(os.path.join(src, skel), 'rb') as fh:
                data = skel2json.convert(fh.read())
            with open(os.path.join(dst, base + '.json'), 'w', encoding='utf-8') as fh:
                json.dump(data, fh, ensure_ascii=False, separators=(',', ':'))
        with open(os.path.join(dst, 'source.txt'), 'w', encoding='utf-8') as fh:
            fh.write(os.path.relpath(os.path.join(src, skel), os.path.dirname(inbox)) + '\n')
        count += 1
    print(f'imported {count} skeletons into {os.path.relpath(OUT, ROOT)}')


def build_catalog():
    items = []
    for group in sorted(os.listdir(OUT)):
        gdir = os.path.join(OUT, group)
        if not os.path.isdir(gdir):
            continue
        for name in sorted(os.listdir(gdir)):
            d = os.path.join(gdir, name)
            js = os.path.join(d, name + '.json')
            if not os.path.isfile(js):
                continue
            with open(js, encoding='utf-8') as fh:
                data = json.load(fh)
            sk = data['skeleton']
            skins = data.get('skins', {})
            if isinstance(skins, list):
                skins = {s['name']: s.get('attachments', {}) for s in skins}
            kinds = set()
            for skin in skins.values():
                for atts in skin.values():
                    for a in atts.values():
                        kinds.add(a.get('type', 'region'))
            src = ''
            if os.path.isfile(os.path.join(d, 'source.txt')):
                with open(os.path.join(d, 'source.txt'), encoding='utf-8') as fh:
                    src = fh.read().strip()
            w, h = png_size(os.path.join(d, name + '.png'))
            items.append({
                'key': f'{group}/{name}',
                'source': src,
                'spine': sk.get('spine'),
                'size': [round(sk.get('width', 0)), round(sk.get('height', 0))],
                'animations': list(data.get('animations', {})),
                'events': list(data.get('events', {})),
                'atlas': [w, h],
                'attachments': sorted(kinds),
            })
    with open(os.path.join(OUT, 'catalog.json'), 'w', encoding='utf-8') as fh:
        json.dump({'note': 'Generated by tools/import_spine.py. Do not edit by hand.', 'skeletons': items}, fh, ensure_ascii=False, indent=1)
    print(f'catalog: {len(items)} skeletons')


if __name__ == '__main__':
    if len(sys.argv) > 1:
        import_inbox(os.path.abspath(sys.argv[1]))
    build_catalog()
